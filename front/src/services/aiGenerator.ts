import { GeneratedLessonData } from '../types/database';

export async function generateLessonContent(params: {
  lesson: string;
  grade: string;
  difficulty: string;
  questionsCount: number;
  studentName: string;
  parentEmail: string;
  studentId: string;
}): Promise<GeneratedLessonData> {
  const { lesson, grade, difficulty, questionsCount } = params;

  // Simulate network / AI latency
  await new Promise((resolve) => setTimeout(resolve, 2000));

  // Determine subject flavor
  const isBiology = /قلب|دوري|دم|تنفس|خلية|كائن|نبات|عضل/i.test(lesson);
  const isPhysics = /حركة|سرعة|نيوتن|طاقة|قوة|فيزياء|عجلة|جاذبية/i.test(lesson);
  const isChemistry = /ذرة|كيمياء|جدول|تفاعل|عنصر|مركب|إلكترون/i.test(lesson);
  const isMath = /معادلة|جبر|هندسة|تفاضل|مثلث|تربيعي|حساب/i.test(lesson);

  let keyPoints: string[] = [];
  let summary = '';
  let flashcards = [];

  if (isBiology) {
    summary = `درس "${lesson}" يعتبر من أهم موضوعات ${grade}. يركز على بنية الجهاز وأعضائه الأساسية، وتكامل الوظائف الحيوية لنقل الغازات والمغذيات، مع الحفاظ على التوازن الداخلي للجسم ومقاومة الأمراض عبر آليات دفاعية متطورة.`;
    keyPoints = [
      'الأعضاء الرئيسية وبنيتها التشريحية الدقيقة وتكاملها الوظيفي.',
      'مسارات الانتقال الحيوي والتبادل الغازي والغذائي بين الخلايا والأوعية.',
      'أهمية السوائل الحيوية ومكوناتها الخلوية في الحفاظ على ثبات البيئة الداخلية.',
      'العادات الصحية والتغذية السليمة للوقاية من الاضطرابات الشائعة.',
    ];
    flashcards = [
      { front: 'ما الوظيفة الأساسية للقلب؟', back: 'مضخة عضلية مجوفة تدفع الدم غير المؤكسج للرئتين والدم المؤكسج لجميع أنسجة الجسم.' },
      { front: 'ما الفرق بين الشرايين والأوردة؟', back: 'الشرايين جدرانها سميكة وتحمل الدم من القلب، والأوردة ذات صمامات وتعيد الدم إلى القلب.' },
      { front: 'ما دور الصفائح الدموية؟', back: 'أجزاء خلوية تلعب دوراً محورياً في تجلط الدم وتكوين السدادة الواقية لمنع النزيف.' },
      { front: 'ما وظيفة الهيموجلوبين؟', back: 'بروتين غني بالحديد في كرات الدم الحمراء، يرتبط بالأكسجين في الرئتين ويوزعه على خلايا الجسم.' },
    ];
  } else if (isPhysics) {
    summary = `يتناول درس "${lesson}" المبادئ الفيزيائية الأساسية في ${grade}. نناقش فيه العلاقات الرياضية بين القوى، المؤثرات الخارجية، الطاقة والسرعة، وكيفية التعبير عنها بيانيا ومختبرياً.`;
    keyPoints = [
      'تعريف الكميات الفيزيائية الأساسية ووحدات قياسها في النظام الدولي.',
      'العلاقة الطردية والعكسية بين المتغيرات في معادلات الحركة.',
      'تطبيقات واقعية لقوانين نيوتن وحفظ الطاقة في حياتنا اليومية.',
      'الرسم البياني للمسافة والزمن وكيفية استنتاج الميل وحساب السرعة والعجلة.',
    ];
    flashcards = [
      { front: 'ما تعريف السرعة المنتظمة؟', back: 'قطع إزاحات أو مسافات متساوية في أزمنة متساوية، وتكون العجلة في هذه الحالة مساوية للصفر.' },
      { front: 'ما نص القانون الأول لنيوتن؟', back: 'يظل الجسم على حالته من سكون أو حركة منتظمة في خط مستقيم ما لم تؤثر عليه قوة محصلة تغير من حالته.' },
      { front: 'ما الفرق بين الكتلة والوزن؟', back: 'الكتلة مقدار ثابت لا يتغير بتغير المكان، بينما الوزن قوة جذب الأرض وتتغير بتغير الجاذبية.' },
      { front: 'ما قانون العجلة الرياضي؟', back: 'العجلة (a) = (السرعة النهائية v2 - السرعة الابتدائية v1) ÷ التغير في الزمن Δt.' },
    ];
  } else if (isChemistry) {
    summary = `في هذا الدرس من ${grade}، نتعمق في "${lesson}". نستعرض تركيب المادة على المستوى المجهري، مستويات الطاقة الرئيسية والفرعية، وأسس تدرج الخواص الكيميائية.`;
    keyPoints = [
      'النواة ومحتوياتها من بروتونات موجبة ونيوترونات متعادلة الشحنة.',
      'قواعد التوزيع الإلكتروني في مستويات الطاقة السبعة (2n²).',
      'التكافؤ والروابط الكيميائية الأيونية والتساهمية.',
      'تدرج خواص الحجم الذري والسالبية الكهربية والفلزية عبر الدورات والمجموعات.',
    ];
    flashcards = [
      { front: 'ما هو العدد الذري؟', back: 'هو عدد البروتونات الموجبة الموجودة داخل نواة الذرة، وهو يحدد هوية العنصر الكيميائي.' },
      { front: 'لماذا الذرة متعادلة كهربياً؟', back: 'لأن عدد البروتونات الموجبة داخل النواة يتساوى بدقة مع عدد الإلكترونات السالبة التي تدور حولها.' },
      { front: 'ما هي الرابطة التساهمية؟', back: 'رابطة كيميائية تنشأ بين اللافلزات عن طريق مشاركة كل ذرة بعدد من إلكترونات التكافؤ.' },
      { front: 'كم إلكترون يتشبع به المستوى الثاني L؟', back: 'يتشبع بـ 8 إلكترونات وفق العلاقة 2n² حيث n=2.' },
    ];
  } else if (isMath) {
    summary = `يركز هذا الموضوع في ${grade} على مفاهيم "${lesson}". نتدرب على استراتيجيات الحل الجبري والتمثيل البياني والتحقق من صحة النتائج عبر خطوات برهانية متسلسلة.`;
    keyPoints = [
      'تحديد نوع المعادلة أو العلاقة الرياضية ودرجتها ومجال تعريفها.',
      'الخطوات الجبرية للتبسيط ونقل الحدود وإيجاد قيمة المتغير المجهول.',
      'التحقق من صحة الحل بالتعويض في المعادلة الأصلية.',
      'الربط بالمسائل الحياتية والنماذج التطبيقية.',
    ];
    flashcards = [
      { front: 'ما هو القانون العام لحل المعادلة التربيعية؟', back: 'x = [-b ± √(b² - 4ac)] / (2a) حيث a ≠ 0.' },
      { front: 'ما هو المميز وما دلالته؟', back: 'المميز Δ = b² - 4ac؛ إذا كان موجباً فالحلان حقيقيان، وصفراً حل واحد، وسالباً مركبان.' },
      { front: 'ما ميل الخط المستقيم الموازي لمحور السينات؟', back: 'ميله يساوي صفراً، وميل الموازي لمحور الصادات غير معرف.' },
      { front: 'ما حاصل ضرب ميلي مستقيمين متعامدين؟', back: 'حاصل ضرب ميليهما يساوي -1 (m1 × m2 = -1).' },
    ];
  } else {
    summary = `شرح شامل ومبسط لدرس "${lesson}" المقرر لطلاب ${grade} بمستوى "${difficulty}". يستعرض المفاهيم الجوهرية والتطبيقات العلمية بأسلوب شائق يرسخ الفهم والتفوق الأكاديمي.`;
    keyPoints = [
      'المفاهيم والنظريات الأساسية المرتبطة بموضوع الدرس.',
      'الربط العملي بين الجانب النظري والتطبيقات الواقعية.',
      'أهم المصطلحات العلمية الواجب إتقانها للاختبارات الرسمية.',
      'نصائح ذهبية وطرق استذكار واسترجاع سريعة للأفكار الرئيسية.',
    ];
    flashcards = [
      { front: `ما الفكرة الجوهرية لـ "${lesson}"؟`, back: `هي القاعدة الأساسية التي تبنى عليها بقية القوانين والمفاهيم في هذا الفصل الدراسي.` },
      { front: `كيف نطبق "${lesson}" في الحياة العملية؟`, back: `من خلال الملاحظة الدقيقة وتطبيق القواعد المنظمة والتجريب المنهجي.` },
      { front: `ما أهم تحدٍ قد يواجه الطالب في هذا الدرس؟`, back: `الخلط بين المفاهيم المتقاربة، ويتم التغلب عليه بالتدريب المستمر وحل الأسئلة.` },
      { front: `ما نصيحة المعلم للتفوق في "${lesson}"؟`, back: `الربط بين الفهم والاستنتاج وحل المسائل دون الاكتفاء بالحفظ المجرد.` },
    ];
  }

  // Generate dynamic quiz questions based on questionsCount
  const pool = [
    {
      q: `أي من العبارات التالية تصف بدقة المفهوم الأساسي في موضوع "${lesson}"؟`,
      choices: [
        'هو الأساس العلمي الذي يفسر الظاهرة بدقة وتوازن',
        'مجرد فرضية نظرية غير قابلة للاختبار',
        'علاقة عكسية دائماً ولا تنطبق على الواقع',
        'مفهوم ينطبق فقط في ظروف مستحيلة التحقق',
      ],
      correctIndex: 0,
      explanation: 'التعريف العلمي المعتمد يوضح أن المفهوم هو الأساس التطبيقي للظاهرة العلمية.',
    },
    {
      q: `عند تطبيق قواعد "${lesson}" بمستوى ${difficulty}، ما النتيجة المترتبة عند زيادة المدخلات؟`,
      choices: [
        'تحدث زيادة متناسبة ومتسقة مع القوانين الحاكمة',
        'تتلاشى المادة كلياً دون أي أثر',
        'يحدث انخفاض عشوائي لا يمكن قياسه',
        'تتوقف القوانين الفيزيائية عن العمل',
      ],
      correctIndex: 0,
      explanation: 'العلاقة التناسبية تضمن استقرار ووضوح النواتج وفق القواعد المقررة بالمنهج.',
    },
    {
      q: `العنصر الأهم الذي يضمن نجاح تطبيق تجارب "${lesson}" هو:`,
      choices: [
        'الدقة في القياس ومراعاة شروط التجربة',
        'التخمين العشوائي للنتائج',
        'تجاهل التغيرات في درجات الحرارة أو المتغيرات',
        'إلغاء خطوات المراجعة والتدقيق',
      ],
      correctIndex: 0,
      explanation: 'الضبط التجريبي والدقة في القياس هما حجر الأساس في العلوم الطبيعية والرياضيات.',
    },
    {
      q: `وفقاً للمقرر الدراسي لـ ${grade}، ما الهدف الأسمى من دراسة هذا الدرس؟`,
      choices: [
        'بناء التفكير النقدي وتطبيقه في حل المشكلات الحياتية',
        'الحفظ الصم دون فهم الاستنتاجات',
        'اجتياز الامتحان فقط ونسيان المفاهيم بعدها',
        'إلغاء التفكير التحليلي والابتكار',
      ],
      correctIndex: 0,
      explanation: 'منظومة التعليم الحديثة تهدف لترسيخ مهارات الفهم والتفكير الإبداعي والتحليلي.',
    },
    {
      q: `ما العامل المشترك بين جميع الحالات المدروسة في "${lesson}"؟`,
      choices: [
        'خضوعها لنفس القوانين والنظريات العلمية الثابتة',
        'اختلافها الكامل دون أي قاعدة تجمعها',
        'عدم إمكانية التنبؤ بسلوكها مستقبلاً',
        'اعتمادها على الصدفة البحتة',
      ],
      correctIndex: 0,
      explanation: 'القوانين العلمية تتسم بالعمومية والثبات عند ثبوت الظروف والعوامل المحيطة.',
    },
    {
      q: `أي مما يلي يعتبر تطبيقاً مباشراً لـ "${lesson}" في التكنولوجيا والطب الحديث؟`,
      choices: [
        'تطوير أجهزة الفحص المتقدمة والأنظمة الذكية',
        'إيقاف الأبحاث العلمية والاستغناء عن التكنولوجيا',
        'العودة للأساليب البدائية في التشخيص',
        'منع الطلاب من استخدام الحواسيب',
      ],
      correctIndex: 0,
      explanation: 'المفاهيم العلمية تتحول لاختراعات وتقنيات طبية وصناعية تخدم البشرية.',
    },
    {
      q: `إذا أردنا التحقق من صحة استنتاج متعلق بـ "${lesson}"، ما الخطوة الأولى؟`,
      choices: [
        'جمع البيانات وتحليلها بموضوعية',
        'إصدار حكم مسبق قبل التجربة',
        'تجاهل الأدلة المناقضة',
        'الاعتماد على الشائعات غير الموثقة',
      ],
      correctIndex: 0,
      explanation: 'المنهج العلمي السليم يبدأ بجمع البيانات والملاحظة المنظمة قبل استخلاص النتائج.',
    },
  ];

  const questions = [];
  for (let i = 0; i < questionsCount; i++) {
    const template = pool[i % pool.length];
    questions.push({
      question: `سؤال ${i + 1}: ${template.q}`,
      choices: template.choices,
      correctIndex: template.correctIndex,
      explanation: template.explanation,
    });
  }

  return {
    title: lesson,
    grade,
    difficulty,
    summary,
    keyPoints,
    flashcards,
    questions,
  };
}
